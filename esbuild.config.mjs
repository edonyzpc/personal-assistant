import { build as esbuildBuild, context } from 'esbuild';
import process from 'process';
import { copy } from 'esbuild-plugin-copy';
import path from 'node:path';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import {
	readFtsIosProductionBuildInputEvidence,
	writeFtsIosLocalProductionBuildProvenance,
} from './scripts/lib/fts-ios-runtime-artifact.mjs';

const banner =
	`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

// Mark every Node builtin import as external so Obsidian Mobile WebView never tries
// to require missing builtins at runtime. Catches both `node:*` (modern) and bare names
// like `worker_threads`/`crypto` (legacy) from transitive LangChain dependencies.
// Maintained list mirrors `NODE_BUILTIN_NAMES` in scripts/audit-bundle.mjs.
const NODE_BUILTIN_BARE = /^(?:fs|path|child_process|os|crypto|stream|url|net|tls|http|https|zlib|querystring|readline|buffer|events|util|tty|dns|module|process|worker_threads|fs\/promises|stream\/promises)$/;
const externalNodeBuiltinsPlugin = {
	name: "external-node-builtins",
	setup(build) {
		build.onResolve({ filter: /^node:/ }, (args) => ({ path: args.path, external: true }));
		build.onResolve({ filter: NODE_BUILTIN_BARE }, (args) => ({ path: args.path, external: true }));
	},
};

const createInlineSqliteWorkerPlugin = (production) => ({
	name: "inline-sqlite-worker",
	setup(build) {
		build.onResolve({ filter: /\?worker-source$/ }, (args) => {
			const sourcePath = args.path.replace(/\?worker-source$/, "");
			return {
				path: path.resolve(args.resolveDir, sourcePath),
				namespace: "sqlite-worker-source",
			};
		});

		build.onLoad({ filter: /.*/, namespace: "sqlite-worker-source" }, async (args) => {
			const result = await esbuildBuild({
				platform: "browser",
				mainFields: ["browser", "module", "main"],
				conditions: ["browser"],
				entryPoints: [args.path],
				bundle: true,
				format: "esm",
				target: "es2020",
				logLevel: "silent",
				write: false,
				metafile: true,
				minify: production ? true : false,
				sourcemap: false,
				loader: {
					'.ts': 'ts',
					'.js': 'js',
					'.mjs': 'js',
				},
				define: {
					"process.env.NODE_ENV": production ? '"production"' : '"development"',
				},
			});
			return {
				contents: `export default ${JSON.stringify(result.outputFiles[0].text)};`,
				loader: "js",
				watchFiles: Object.keys(result.metafile.inputs),
			};
		});
	},
});

// Lazy binary loader: keeps WASM/font base64 in the bundle (Obsidian plugins ship as one
// main.js), but defers conversion until first use. WASM becomes a Uint8Array; Share Card
// consumes its WOFF2 as a data URL directly, avoiding an atob -> bytes -> btoa round trip.
const lazyBinaryPlugin = {
	name: "lazy-binary",
	setup(build) {
		// No onResolve: let esbuild's default resolver walk node_modules so bare imports
		// like `@sqliteai/sqlite-wasm/sqlite3.wasm` end up with an absolute on-disk path.
		// onLoad in the default `file` namespace then handles the bytes.
		build.onLoad({ filter: /\.(wasm|woff2)$/ }, async (args) => {
			const bytes = await readFile(args.path);
			const base64 = bytes.toString("base64");
			return {
				contents: `
var _b64 = ${JSON.stringify(base64)};
var _decoded = null;
var _decoding = null;
var _fontDataUrl = null;
export default function getBinary() {
    if (_decoded !== null) return _decoded;
    var b = atob(_b64);
    _decoded = new Uint8Array(b.length);
    for (var i = 0; i < b.length; i++) _decoded[i] = b.charCodeAt(i);
    _b64 = null;
    return _decoded;
}
export function getBinaryAsync() {
    if (_decoded !== null) return Promise.resolve(_decoded);
    if (_decoding !== null) return _decoding;
    _decoding = Promise.resolve().then(() => {
        if (_decoded !== null) return _decoded;
        var b = atob(_b64);
        _decoded = new Uint8Array(b.length);
        for (var i = 0; i < b.length; i++) _decoded[i] = b.charCodeAt(i);
        _b64 = null;
        return _decoded;
    });
    return _decoding;
}
export var getSqliteWasmBinary = getBinary;
export var getSqliteWasmBinaryAsync = getBinaryAsync;
export function getShareCardFontDataUrlAsync() {
    if (_fontDataUrl !== null) return Promise.resolve(_fontDataUrl);
    if (_b64 === null) return Promise.reject(new Error("Bundled font base64 is unavailable."));
    _fontDataUrl = "data:font/woff2;base64," + _b64;
    _b64 = null;
    return Promise.resolve(_fontDataUrl);
}
`,
				loader: "js",
				watchFiles: [args.path],
			};
		});
	},
};

function createMainBuildOptions({
	absWorkingDir = process.cwd(),
	production,
	copyAssets,
	logLevel = "info",
	write = true,
}) {
	return {
		absWorkingDir,
		platform: "browser",
		mainFields: ["browser", "module", "main"],
		conditions: ["browser"],
		banner: {
			js: banner,
		},
		entryPoints: ["src/main.ts"],
		bundle: true,
		external: [
			"obsidian",
			"electron",
			// Mobile-compat note: ALL `node:*` builtins are additionally marked external via
			// the `externalNodeBuiltinsPlugin` below (esbuild's `external` field accepts only
			// strings; regex matching must be done in a plugin). Obsidian Mobile WebView throws
			// when these modules are required, so this is mobile compatibility, NOT size opt.
			"@codemirror/autocomplete",
			"@codemirror/collab",
			"@codemirror/commands",
			"@codemirror/language",
			"@codemirror/lint",
			"@codemirror/search",
			"@codemirror/state",
			"@codemirror/view",
			"@lezer/common",
			"@lezer/highlight",
			"@lezer/lr"],
		format: "cjs",
		target: "es2020",
		logLevel,
		sourcemap: production ? false : "inline",
		treeShaking: true,
		outfile: "dist/main.js",
		write,
		minify: production ? true : false,
		loader: {
			'.ts': 'ts',
			'.tsx': 'tsx',
			'.js': 'js',
			'.jsx': 'jsx',
			'.md': 'text',
			'.txt': 'text',
			// `.wasm` is handled by `lazyBinaryPlugin` (see plugin block above) — not via the
			// `binary` loader anymore. The plugin keeps the base64 string inline but defers
			// atob+Uint8Array decoding until first use, saving ~941KB of plugin-load heap and
			// allowing GC to reclaim the base64 string after decode.
		},
		define: {
			"process.env.NODE_ENV": production ? '"production"' : '"development"',
		},
		splitting: false,
		plugins: [
			...(copyAssets ? [copy({
				assets: [
					{
						from: ['./manifest.json'],
						to: ['manifest.json'],
					},
					{
						from: ['./manifest-beta.json'],
						to: ['manifest-beta.json'],
					},
					{
						from: ['./styles.css'],
						to: ['styles.css'],
					},
				],
			})] : []),
			createInlineSqliteWorkerPlugin(production),
			lazyBinaryPlugin,
			externalNodeBuiltinsPlugin,
		],
	};
}

export async function buildProductionMainArtifactInMemory(options = {}) {
	const result = await esbuildBuild(createMainBuildOptions({
		absWorkingDir: options.absWorkingDir ?? process.cwd(),
		production: true,
		copyAssets: false,
		logLevel: "silent",
		write: false,
	}));
	const output = result.outputFiles?.find((file) => file.path.endsWith("/dist/main.js"))
		?? result.outputFiles?.[0];
	if (!output) throw new Error("The deterministic production rebuild produced no main.js.");
	return {
		source: output.text,
		byteLength: output.contents.byteLength,
	};
}

const isExecutedDirectly = process.argv[1]
	&& path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isExecutedDirectly) {
	const production = process.argv[2] === "production";
	const mainContext = await context(createMainBuildOptions({
		production,
		copyAssets: true,
	}));
	if (production) {
		const productionInputsBeforeBuild = await readFtsIosProductionBuildInputEvidence();
		await mainContext.rebuild();
		await writeFtsIosLocalProductionBuildProvenance({
			expectedBuildInputs: productionInputsBeforeBuild,
		});
		process.exit(0);
	} else {
		await mainContext.watch();
	}
}
